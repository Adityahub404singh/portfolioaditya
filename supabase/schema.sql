-- Run this script in Supabase SQL Editor.
-- Replace YOUR_ADMIN_EMAIL@example.com with the email used for Supabase Auth.

create table if not exists public.portfolio_content (
  id integer primary key check (id = 1),
  content jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.portfolio_content enable row level security;

drop policy if exists "Public can read portfolio content" on public.portfolio_content;
create policy "Public can read portfolio content"
  on public.portfolio_content for select using (true);

drop policy if exists "Admin can insert portfolio content" on public.portfolio_content;
create policy "Admin can insert portfolio content"
  on public.portfolio_content for insert to authenticated
  with check (lower((auth.jwt() ->> 'email')) = lower('YOUR_ADMIN_EMAIL@example.com'));

drop policy if exists "Admin can update portfolio content" on public.portfolio_content;
create policy "Admin can update portfolio content"
  on public.portfolio_content for update to authenticated
  using (lower((auth.jwt() ->> 'email')) = lower('YOUR_ADMIN_EMAIL@example.com'))
  with check (lower((auth.jwt() ->> 'email')) = lower('YOUR_ADMIN_EMAIL@example.com'));

-- Initial public content is loaded from src/data.js until the first admin publish.
-- Optional public storage bucket for certificate scans and portfolio media.
insert into storage.buckets (id, name, public)
values ('portfolio-assets', 'portfolio-assets', true)
on conflict (id) do nothing;

drop policy if exists "Public can read portfolio assets" on storage.objects;
create policy "Public can read portfolio assets"
  on storage.objects for select
  using (bucket_id = 'portfolio-assets');

drop policy if exists "Admin can upload portfolio assets" on storage.objects;
create policy "Admin can upload portfolio assets"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'portfolio-assets'
    and lower((auth.jwt() ->> 'email')) = lower('YOUR_ADMIN_EMAIL@example.com')
  );

drop policy if exists "Admin can update portfolio assets" on storage.objects;
create policy "Admin can update portfolio assets"
  on storage.objects for update to authenticated
  using (
    bucket_id = 'portfolio-assets'
    and lower((auth.jwt() ->> 'email')) = lower('YOUR_ADMIN_EMAIL@example.com')
  )
  with check (
    bucket_id = 'portfolio-assets'
    and lower((auth.jwt() ->> 'email')) = lower('YOUR_ADMIN_EMAIL@example.com')
  );

-- Anonymous portfolio analytics: page views and project clicks only.
-- Do not store visitor names, email addresses, or raw IP addresses.
create table if not exists public.portfolio_events (
  id bigint generated by default as identity primary key,
  event_type text not null check (event_type in ('page_view','project_click')),
  page_path text,
  referrer text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
alter table public.portfolio_events enable row level security;

drop policy if exists "Anyone can record portfolio analytics" on public.portfolio_events;
create policy "Anyone can record portfolio analytics"
  on public.portfolio_events for insert to anon, authenticated
  with check (event_type in ('page_view','project_click'));

drop policy if exists "Admin can read portfolio analytics" on public.portfolio_events;
create policy "Admin can read portfolio analytics"
  on public.portfolio_events for select to authenticated
  using (lower((auth.jwt() ->> 'email')) = lower('YOUR_ADMIN_EMAIL@example.com'));

create index if not exists portfolio_events_created_at_idx
  on public.portfolio_events (created_at desc);
